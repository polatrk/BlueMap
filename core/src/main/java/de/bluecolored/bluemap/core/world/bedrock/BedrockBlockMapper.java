package de.bluecolored.bluemap.core.world.bedrock;

import de.bluecolored.bluemap.core.logger.Logger;
import de.bluecolored.bluemap.core.util.Key;
import de.bluecolored.bluemap.core.world.BlockState;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.*;
import java.util.concurrent.ConcurrentHashMap;
import java.util.zip.GZIPInputStream;

/**
 * Translates Bedrock block states (palette entries) into the equivalent Java block states, so that
 * BlueMap can render Bedrock worlds with the Java resource pack.
 *
 * <p>The table (resources/de/bluecolored/bluemap/bedrock/bedrock-blocks.txt.gz) is generated by
 * implementations/bedrock/tools/generate-mappings.mjs from GeyserMC's mappings (MIT) and the Java
 * data generator report of the matching version. Bedrock states missing from the table (older
 * worlds, extra states) are matched to the closest known state of the same block.</p>
 */
public final class BedrockBlockMapper {

    private static final String RESOURCE = "/de/bluecolored/bluemap/bedrock/bedrock-blocks.txt.gz";
    private static final Map<String, String> NAME_ALIASES = Map.of(
            "minecraft:flowing_water", "minecraft:water",
            "minecraft:flowing_lava", "minecraft:lava"
    );

    private static volatile BedrockBlockMapper instance;

    private record Candidate(Map<String, String> states, BlockState java) {}

    private final Map<String, BlockState> exact = new HashMap<>();
    private final Map<String, List<Candidate>> byName = new HashMap<>();
    private final Map<String, BlockState> resolved = new ConcurrentHashMap<>();
    private final Map<BlockState, BlockState> waterlogged = new ConcurrentHashMap<>();
    private final Set<String> reported = ConcurrentHashMap.newKeySet();

    public static BedrockBlockMapper get() {
        BedrockBlockMapper m = instance;
        if (m == null) {
            synchronized (BedrockBlockMapper.class) {
                if (instance == null) instance = new BedrockBlockMapper();
                m = instance;
            }
        }
        return m;
    }

    private BedrockBlockMapper() {
        try (InputStream in = BedrockBlockMapper.class.getResourceAsStream(RESOURCE)) {
            if (in == null) throw new IOException("missing " + RESOURCE);
            BufferedReader reader = new BufferedReader(new InputStreamReader(new GZIPInputStream(in), StandardCharsets.UTF_8));
            Map<String, BlockState> javaStates = new HashMap<>();
            String line;
            while ((line = reader.readLine()) != null) {
                String[] parts = line.split("\t", -1);
                if (parts.length != 3) continue;
                BlockState java = javaStates.computeIfAbsent(parts[2], BedrockBlockMapper::parseJavaState);
                exact.put(parts[0] + "\t" + parts[1], java);
                byName.computeIfAbsent(parts[0], k -> new ArrayList<>()).add(new Candidate(parseStates(parts[1]), java));
            }
        } catch (IOException ex) {
            throw new IllegalStateException("Failed to load the Bedrock block mappings", ex);
        }
    }

    /** Java state for a Bedrock palette entry ({@code name}, {@code states} compound). */
    public BlockState map(String name, Map<String, Object> states) {
        if (!name.contains(":")) name = "minecraft:" + name;
        String key = name + "\t" + stateKey(states);
        BlockState s = exact.get(key);
        if (s != null) return s;
        return resolved.computeIfAbsent(key, k -> resolve(k.substring(0, k.indexOf('\t')), states));
    }

    private BlockState resolve(String name, Map<String, Object> states) {
        List<Candidate> candidates = byName.get(name);
        if (candidates == null && NAME_ALIASES.containsKey(name)) candidates = byName.get(NAME_ALIASES.get(name));
        if (candidates != null) {
            // Closest known state: most equal properties, fewest differing ones.
            Candidate best = null;
            int bestScore = Integer.MIN_VALUE;
            for (Candidate c : candidates) {
                int score = 0;
                for (Map.Entry<String, String> e : c.states.entrySet()) {
                    Object v = states.get(e.getKey());
                    score += v != null && e.getValue().equals(String.valueOf(v)) ? 2 : -1;
                }
                if (score > bestScore) { bestScore = score; best = c; }
            }
            if (best != null) return best.java;
        }
        // Many blocks share their name with Java: try the Java default state of the same id.
        if (reported.add(name)) Logger.global.logDebug("No Bedrock mapping for '" + name + "', trying the Java block of the same name.");
        return new BlockState(Key.parse(name, Key.MINECRAFT_NAMESPACE));
    }

    /** Variant of a Java state with waterlogged=true (Bedrock stores the water in a second block layer). */
    public BlockState waterlogged(BlockState state) {
        if (state.isWaterlogged() || !state.getProperties().containsKey("waterlogged")) return state;
        return waterlogged.computeIfAbsent(state, s -> {
            Map<String, String> props = new HashMap<>(s.getProperties());
            props.put("waterlogged", "true");
            return new BlockState(s.getId(), props);
        });
    }

    static String stateKey(Map<String, Object> states) {
        if (states == null || states.isEmpty()) return "";
        List<String> keys = new ArrayList<>(states.keySet());
        Collections.sort(keys);
        StringBuilder sb = new StringBuilder();
        for (String k : keys) {
            if (!sb.isEmpty()) sb.append(',');
            sb.append(k).append('=').append(states.get(k));
        }
        return sb.toString();
    }

    private static Map<String, String> parseStates(String s) {
        if (s.isEmpty()) return Map.of();
        Map<String, String> m = new HashMap<>();
        for (String kv : s.split(",")) {
            int i = kv.indexOf('=');
            m.put(kv.substring(0, i), kv.substring(i + 1));
        }
        return m;
    }

    /** Parses {@code minecraft:oak_fence[east=false,north=true]}. */
    static BlockState parseJavaState(String s) {
        int b = s.indexOf('[');
        if (b < 0) return new BlockState(Key.parse(s, Key.MINECRAFT_NAMESPACE));
        Map<String, String> props = new LinkedHashMap<>();
        for (String kv : s.substring(b + 1, s.length() - 1).split(",")) {
            int i = kv.indexOf('=');
            props.put(kv.substring(0, i), kv.substring(i + 1));
        }
        return new BlockState(Key.parse(s.substring(0, b), Key.MINECRAFT_NAMESPACE), props);
    }
}
