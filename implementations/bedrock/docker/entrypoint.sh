#!/bin/sh
# Prepares the BlueMap config from environment variables on the first start, then runs BlueMap.
#
#   /server-data       BDS server folder (server.properties, worlds/), mounted read-only
#   /data              BlueMap data: configs (bluemap/), map tiles, ssh key
#
# Environment:
#   BDS_SSH            user@host of the BDS machine (bluemap-bridge.sh as forced command), empty = no console
#   SSH_PORT           ssh port (22)
#   ACCEPT_DOWNLOAD    download of the Minecraft resources from Mojang, needed to render ("true" by default,
#                      i.e. the Minecraft EULA is accepted for it; "false" to refuse)
#   RENDER_THREADS     render threads (2)
#   RENDER_CAVES       "yes" to render underground (needed by the Layers (Y) view), default "no"
#   SAVE_INTERVAL      seconds between forced BDS saves (30)
#   ADDON_PORT / ADDON_TOKEN   HTTP endpoint for the "net" add-on variant (0 = off)
#   JAVA_OPTS          JVM options (-Xmx...)
set -eu

DATA=/data
CONF="$DATA/bluemap"
mkdir -p "$CONF" "$DATA/ssh"
[ -f /server-data/server.properties ] || echo "WARNING: /server-data/server.properties not found, mount the BDS folder on /server-data"

if [ -n "${BDS_SSH:-}" ]; then
  KEY="$DATA/ssh/id_ed25519"
  if [ ! -f "$KEY" ]; then
    ssh-keygen -q -t ed25519 -N "" -C "bluemap" -f "$KEY"
  fi
  echo "------------------------------------------------------------------------------"
  echo "BlueMap ssh public key. On the BDS machine, add this line to"
  echo "~/.ssh/authorized_keys of the user in BDS_SSH (see README.md):"
  echo
  echo "command=\"/usr/local/bin/bluemap-bridge.sh\",no-pty,no-port-forwarding,no-agent-forwarding,no-X11-forwarding $(cat "$KEY.pub")"
  echo "------------------------------------------------------------------------------"
  SSH="ssh -i $KEY -p ${SSH_PORT:-22} -o BatchMode=yes -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=$DATA/ssh/known_hosts -o ServerAliveInterval=30 -o ServerAliveCountMax=3 $BDS_SSH"
  MODE=external
  CONSOLE_COMMAND="$SSH logs"
  COMMAND_TEMPLATE="$SSH cmd"
else
  MODE=none
  CONSOLE_COMMAND=""
  COMMAND_TEMPLATE=""
fi

# bedrock.conf is rewritten at every start from the environment.
cat > "$CONF/bedrock.conf" <<CONF_EOF
# Generated by entrypoint.sh from the container environment (changes are overwritten).
bds-folder: "/server-data"
console-mode: "$MODE"
bedrock-command: ""
console-command: "$CONSOLE_COMMAND"
command-template: "$COMMAND_TEMPLATE"
save-interval: ${SAVE_INTERVAL:-30}
addon-port: ${ADDON_PORT:-0}
addon-token: "${ADDON_TOKEN:-}"
CONF_EOF

# First start: let BlueMap write its default configs, then adapt them.
if [ ! -f "$CONF/core.conf" ]; then
  echo "Generating the BlueMap configs..."
  timeout 120 java -jar /app/bluemap-bedrock.jar -c bluemap </dev/null >/dev/null 2>&1 || true
  if [ -f "$CONF/core.conf" ]; then
    sed -i "s/^render-thread-count: .*/render-thread-count: ${RENDER_THREADS:-2}/" "$CONF/core.conf"
    sed -i 's/^hires-slider-max: .*/hires-slider-max: 1500/; s/^hires-slider-default: .*/hires-slider-default: 350/; s/^lowres-slider-max: .*/lowres-slider-max: 10000/; s/^lowres-slider-default: .*/lowres-slider-default: 3000/' "$CONF/webapp.conf"
    if [ "${RENDER_CAVES:-no}" = "yes" ]; then
      sed -i 's/^remove-caves-below-y: .*/remove-caves-below-y: -10000/' "$CONF"/maps/*.conf
    fi
  fi
fi
if [ -f "$CONF/core.conf" ]; then
  if [ "${ACCEPT_DOWNLOAD:-true}" = "true" ]; then
    sed -i 's/^accept-download: .*/accept-download: true/' "$CONF/core.conf"
  else
    echo "ACCEPT_DOWNLOAD is not \"true\": BlueMap cannot download the Minecraft resources it needs to render."
  fi
fi

# shellcheck disable=SC2086
exec java ${JAVA_OPTS:-} -jar /app/bluemap-bedrock.jar -c bluemap
